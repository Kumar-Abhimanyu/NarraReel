"""ASS subtitle writer (WHAT_TO_DO.md section 5.9.4).

One Dialogue event per spoken word: it contains the whole chunk with the active word styled
through override tags, so colour, scale and box are exact for every word. Every word carries its
complete state (no reverts), which keeps entry animations correct.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

from ..models import ScriptAnalysis, WordTiming
from .chunk import CaptionChunk, CapWord, build_cap_words, chunk_words
from .colors import ass_style_color, ass_tag_alpha, ass_tag_color
from .fonts import FontInfo, get_font, measure_font, missing_glyphs, text_width
from .formats import VideoFormat
from .styles import CaptionStyle


def ass_time(seconds: float) -> str:
    cs = max(0, round(seconds * 100))
    h, cs = divmod(cs, 360_000)
    m, cs = divmod(cs, 6000)
    s, cs = divmod(cs, 100)
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def escape_text(text: str) -> str:
    """ASS has no clean escape for braces/backslashes in text; drop them."""
    return text.replace("\\", "").replace("{", "").replace("}", "").replace("\n", " ")


def _pct(scale: float) -> int:
    return round(scale * 100)


def _style_line(style: CaptionStyle, font: FontInfo) -> str:
    box = style.border_style == "box" and style.colors.box
    border_style = 3 if box else 1
    outline_colour = ass_style_color(style.colors.box) if box else ass_style_color(style.colors.outline)
    fields = [
        "Main", font.ass_family, str(style.font.size),
        ass_style_color(style.colors.text), ass_style_color(style.colors.highlight),
        outline_colour, ass_style_color(style.colors.shadow),
        "-1" if font.ass_bold else "0", "0", "0", "0", "100", "100",
        f"{style.font.letter_spacing:g}", "0", str(border_style),
        f"{style.outline_width:g}", f"{style.shadow_offset:g}", "5", "0", "0", "0", "1",
    ]  # fmt: skip
    return "Style: " + ",".join(fields)


def header(style: CaptionStyle, font: FontInfo, fmt: VideoFormat) -> str:
    return "\n".join([
        "[Script Info]",
        "; Generated by NarraReel",
        "ScriptType: v4.00+",
        f"PlayResX: {fmt.width}",
        f"PlayResY: {fmt.height}",
        "WrapStyle: 2",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: None",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
        "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
        "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        _style_line(style, font),
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]) + "\n"  # fmt: skip


@dataclass
class _WordState:
    color: str
    scale: float
    box: bool


def _word_state(style: CaptionStyle, word: CapWord, active: bool) -> _WordState:
    colors, hl, em = style.colors, style.highlight, style.emphasis
    color, scale, box = colors.text, 1.0, False
    if word.emphasis and em.enabled:
        color, scale = em.color, em.scale
    if active and hl.mode != "none":
        scale = max(scale, hl.scale) if word.emphasis else hl.scale
        if hl.box:
            box = True
        else:
            color = colors.highlight
    return _WordState(color, scale, box)


def _word_tags(style: CaptionStyle, st: _WordState, intro: str | None, dur_ms: int) -> str:
    s = _pct(st.scale)
    tags = [f"\\c{ass_tag_color(st.color)}"]
    if st.box:
        box_c = style.highlight.box_color
        tags.append(
            f"\\bord{style.highlight.box_padding + style.outline_width:g}"
            f"\\3c{ass_tag_color(box_c)}\\3a{ass_tag_alpha(box_c)}\\shad0"
        )
    else:
        box_style = style.border_style == "box" and style.colors.box
        out_c = style.colors.box if box_style else style.colors.outline
        tags.append(
            f"\\bord{style.outline_width:g}\\3c{ass_tag_color(out_c)}\\3a{ass_tag_alpha(out_c)}"
            f"\\shad{style.shadow_offset:g}"
        )
    if intro == "pop":
        s0 = round(s * 0.8)
        tags.append(f"\\fscx{s0}\\fscy{s0}\\t(0,{dur_ms},\\fscx{s}\\fscy{s})")
    elif intro == "bounce":
        s0, s1 = round(s * 0.7), round(s * 1.12)
        mid = round(dur_ms * 0.6)
        tags.append(
            f"\\fscx{s0}\\fscy{s0}\\t(0,{mid},\\fscx{s1}\\fscy{s1})"
            f"\\t({mid},{dur_ms},\\fscx{s}\\fscy{s})"
        )
    else:
        tags.append(f"\\fscx{s}\\fscy{s}")
    return "{" + "".join(tags) + "}"


def _event_text(
    style: CaptionStyle, chunk: CaptionChunk, active: int | None, intro: str | None
) -> str:
    # a box highlight eats into the gap between words, so give those styles a wider one
    separator = "  " if style.highlight.box and style.highlight.mode != "none" else " "
    lines = []
    for line in chunk.lines:
        parts = []
        for wi in line:
            w = chunk.words[wi]
            st = _word_state(style, w, active == wi)
            tags = _word_tags(style, st, intro, style.animation.duration_ms)
            parts.append(tags + escape_text(w.text))
        lines.append(separator.join(parts))
    return "\\N".join(lines)


def chunk_events(
    style: CaptionStyle, fmt: VideoFormat, chunk: CaptionChunk, x: int, y: int, an: int = 5
) -> list[str]:
    anim = style.animation
    mode = style.highlight.mode
    base = f"\\an{an}\\pos({x},{y})"
    if style.blur:
        base += f"\\blur{style.blur:g}"

    if mode == "none":
        boundaries = [(chunk.start, chunk.end, None)]
    else:
        boundaries = []
        for k, w in enumerate(chunk.words):
            start = w.start if k else chunk.start
            end = chunk.words[k + 1].start if k + 1 < len(chunk.words) else chunk.end
            boundaries.append((start, max(end, start + 0.02), k))

    events = []
    last = len(boundaries) - 1
    for n, (start, end, active) in enumerate(boundaries):
        intro = anim.in_ if (n == 0 and anim.in_ in ("pop", "bounce") and anim.duration_ms) else None
        fade = ""
        if anim.in_ == "fade" and anim.duration_ms:
            fade_in = anim.duration_ms if n == 0 else 0
            fade_out = 60 if n == last else 0
            if fade_in or fade_out:
                fade = f"\\fad({fade_in},{fade_out})"
        text = _event_text(style, chunk, active, intro)
        events.append(
            f"Dialogue: 0,{ass_time(start)},{ass_time(end)},Main,,0,0,0,,{{{base}{fade}}}{text}"
        )
    return events


@dataclass
class CaptionResult:
    ass: str
    chunks: list[CaptionChunk]
    font: FontInfo
    warnings: list[str]


def build_captions(
    words: Sequence[WordTiming],
    analysis: ScriptAnalysis,
    style: CaptionStyle,
    fmt: VideoFormat,
    keep_emoji: bool = False,
) -> CaptionResult:
    """Words with timings -> ASS file text (plus the chunks, for previews and tests)."""
    font = get_font(style.font.id)
    cap_words = build_cap_words(words, analysis, style, keep_emoji)
    warnings: list[str] = []
    lacking = missing_glyphs(font, "".join(w.text for w in cap_words))
    if lacking:
        sample = " ".join(sorted(lacking)[:8])
        hint = " Try Noto Sans Devanagari." if any("ऀ" <= c <= "ॿ" for c in lacking) else ""
        warnings.append(f"{font.display_name} can't show these characters: {sample}.{hint}")

    pil = measure_font(font, style.font.size)
    spacing = style.font.letter_spacing
    pad = style.highlight.box_padding if style.highlight.box else 0
    # Active/emphasised words are drawn larger; budget for the larger of the two scales.
    grow = max(
        style.highlight.scale if style.highlight.mode != "none" else 1.0,
        style.emphasis.scale if style.emphasis.enabled else 1.0,
    )

    def word_width(w: CapWord) -> float:
        return text_width(pil, w.text, spacing) * grow + 2 * pad

    space = text_width(pil, "  " if pad else " ", spacing)
    x, an, room = fmt.anchor_x(style.layout.align_x, style.layout.offset_x)
    chunks = chunk_words(cap_words, style, word_width, space, room)

    y = fmt.position_y(style.layout.position, style.layout.offset_y)
    out = [header(style, font, fmt)]
    for chunk in chunks:
        out.extend(e + "\n" for e in chunk_events(style, fmt, chunk, x, y, an))
    return CaptionResult("".join(out), chunks, font, warnings)
